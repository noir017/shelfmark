func TestDetect(t *testing.T) {
	cases := []struct {
		body string
		want error
	}{
		{`{"ciphertext":"abc","salt":"def"}`, ErrEncrypted},
		{"  \n{\"ciphertext\":\"x\"}", ErrEncrypted},
		{"U2FsdGVkX1+abcdef==", ErrNotXBEL},
		{"<!DOCTYPE NETSCAPE-Bookmark-file-1>\n<DL></DL>", ErrHTML},
		{"<xbel></xbel>", ErrNotXBEL},
		{Header + "<html></html>", ErrNotXBEL},
	}
	for _, c := range cases {
		_, err := Parse([]byte(c.body))
		if !errors.Is(err, c.want) {
			t.Errorf("%q: err %v, want %v", c.body, err, c.want)
		}
	}
}

func TestParseErrors(t *testing.T) {
	bad := map[string]string{
		"duplicate": Header + `<xbel><bookmark href="a" id="1"/><folder id="1"><title>x</title></folder></xbel>`,
		"zero":      Header + `<xbel><bookmark href="a" id="0"/></xbel>`,
		"broken":    Header + `<xbel><folder id="1"><title>x</title></xbel>`,
		"unclosed":  Header + `<xbel><folder id="1">`,
	}
	for name, body := range bad {
		_, err := Parse([]byte(body))
		var pe *ParseError
		if !errors.As(err, &pe) {
			t.Errorf("%s: err %v, want ParseError", name, err)
		}
	}
	deep := Header + "<xbel>" + strings.Repeat(`<folder><title>x</title>`, MaxDepth+1) + strings.Repeat("</folder>", MaxDepth+1) + "</xbel>"
	var pe *ParseError
	if _, err := Parse([]byte(deep)); !errors.As(err, &pe) {
		t.Fatalf("deep: %v", err)
	}
	ok := Header + "<xbel>" + strings.Repeat(`<folder><title>x</title>`, MaxDepth) + strings.Repeat("</folder>", MaxDepth) + "</xbel>"
	if _, err := Parse([]byte(ok)); err != nil {
		t.Fatalf("depth %d should parse: %v", MaxDepth, err)
	}
}

func TestParseLenient(t *testing.T) {
	// control characters are dropped, unknown entities kept literally, external entities ignored
	body := Header + `<!DOCTYPE xbel [<!ENTITY xxe SYSTEM "file:///etc/passwd">]><xbel>` +
		"<bookmark href=\"https://example.com/\" id=\"1\"><title>a\x01b &nbsp; &xxe;</title></bookmark></xbel>"
	doc, err := Parse([]byte(body))
	if err != nil {
		t.Fatal(err)
	}
	if got := doc.Items[0].Title; got != "ab &nbsp; &xxe;" {
		t.Fatalf("title %q", got)
	}
}

