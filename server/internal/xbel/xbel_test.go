type fixtureItem struct {
	Type     string         `json:"type"`
	ID       int64          `json:"id"`
	URL      *string        `json:"url"`
	Title    string         `json:"title"`
	Children []*fixtureItem `json:"children"`
}

type fixture struct {
	HighestID  *int64         `json:"highestId"`
	PersistIDs bool           `json:"persistIds"`
	Children   []*fixtureItem `json:"children"`
}

func loadFixture(t *testing.T, path string) fixture {
	t.Helper()
	raw, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	var f fixture
	if err := json.Unmarshal(raw, &f); err != nil {
		t.Fatal(err)
	}
	return f
}

func compareItems(t *testing.T, path string, got []*Item, want []*fixtureItem) {
	t.Helper()
	if len(got) != len(want) {
		t.Fatalf("%s: %d items, want %d", path, len(got), len(want))
	}
	for i, w := range want {
		g := got[i]
		p := path + "/" + w.Title
		if g.Type != w.Type || g.ID != w.ID || g.Title != w.Title {
			t.Fatalf("%s: got %s id=%d title=%q, want %s id=%d title=%q", p, g.Type, g.ID, g.Title, w.Type, w.ID, w.Title)
		}
		if w.Type == TypeBookmark {
			if w.URL == nil || g.URL != *w.URL {
				t.Fatalf("%s: url %q, want %v", p, g.URL, w.URL)
			}
		}
		compareItems(t, p, g.Children, w.Children)
	}
}

func checkAgainstFloccus(t *testing.T, doc *Doc, f fixture) {
	t.Helper()
	if f.HighestID == nil {
		if doc.HasHighestID {
			t.Fatalf("highestId %d, want none", doc.HighestID)
		}
	} else if !doc.HasHighestID || doc.HighestID != *f.HighestID {
		t.Fatalf("highestId %d (%v), want %d", doc.HighestID, doc.HasHighestID, *f.HighestID)
	}
	if doc.PersistIDs() != f.PersistIDs {
		t.Fatalf("persistIds %v, want %v", doc.PersistIDs(), f.PersistIDs)
	}
	compareItems(t, "", doc.Items, f.Children)
}

// Files generated by testdata/gen.mjs with Floccus' serializer must survive
// parse -> generate byte for byte.
func TestRoundTripFloccusFixtures(t *testing.T) {
	files, _ := filepath.Glob("testdata/roundtrip/*.xbel")
	if len(files) < 4 {
		t.Fatalf("fixtures missing: %v", files)
	}
	for _, file := range files {
		t.Run(filepath.Base(file), func(t *testing.T) {
			raw, err := os.ReadFile(file)
			if err != nil {
				t.Fatal(err)
			}
			doc, err := Parse(raw)
			if err != nil {
				t.Fatal(err)
			}
			checkAgainstFloccus(t, doc, loadFixture(t, strings.TrimSuffix(file, ".xbel")+".json"))
			out := Write(doc.Items, doc.HighestID)
			if !bytes.Equal(out, raw) {
				t.Fatalf("round trip differs\n--- got\n%s\n--- want\n%s", out, raw)
			}
		})
	}
}

// Files written by other programs must parse to what Floccus' parser sees,
